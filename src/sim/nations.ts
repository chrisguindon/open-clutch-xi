export const REGIONS: Region[] = ['Europe', 'South America', 'North & Central America', 'Africa', 'Asia & Oceania'];

export const NATIONS: TeamIdentity[] = SPECS.map((s, i) => ({
  id: s.code.toLowerCase(),
  name: s.name,
  short: s.code,
  iso: s.iso,
  region: s.region,
  flag: `assets/flags/${s.iso}.svg`,
  primary: s.home[0],
  secondary: s.home[1],
  shorts: s.home[2],
  socks: s.home[3],
  pattern: s.home[4],
  trim: s.home[5],
  boots: i % 3 === 0 ? '#111111' : i % 3 === 1 ? '#f8fafc' : s.home[5],
  keeper: s.keeper,
  skinTones: SKIN.map((_, k) => SKIN[(k + i) % SKIN.length]),
  away: { primary: s.away[0], secondary: s.away[1], shorts: s.away[2], socks: s.away[3], pattern: s.away[4], trim: s.away[5] },
}));

export function nationByCode(code: string | undefined): TeamIdentity | undefined {
  return NATIONS.find((n) => n.short === code);
}

/** First-launch default: the player's own country if it is in the list (from the browser locale), else Brazil. */
export function defaultHomeCode(locale = typeof navigator !== 'undefined' ? navigator.language : ''): string {
  const region = locale.split('-')[1]?.toUpperCase();
  const byIso: Record<string, string> = Object.fromEntries(NATIONS.map((n) => [n.iso!.toUpperCase(), n.short]));
  if (region === 'GB') return 'ENG';
  return (region && byIso[region]) || 'BRA';
}
